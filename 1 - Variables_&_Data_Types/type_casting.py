# Type Casting in Python

# Integer to float
number = 10
converted_float = float(number)
print(converted_float)

# Float to integer
price = 25.90
converted_int = int(price)
print(converted_int)  # 25

# Integer to string
age = 19
age_text = str(age)
print(age_text)
print(type(age_text))

# String to integer
value = "100"
converted_value = int(value)
print(converted_value + 50)

# String to float
marks = "85.5"
converted_marks = float(marks)
print(converted_marks)

# Integer to boolean
print(bool(1))  # True
print(bool(0))  # False