
# Bitwise Operators in Python

a = 5  # Binary: 0101
b = 3  # Binary: 0011

# Bitwise AND
print("AND:", a & b)

# Bitwise OR
print("OR:", a | b)

# Bitwise XOR
print("XOR:", a ^ b)

# Bitwise NOT
print("NOT:", ~a)

# Left shift
print("Left Shift:", a << 1)

# Right shift
print("Right Shift:", a >> 1)
