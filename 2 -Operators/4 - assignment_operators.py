
# Assignment Operators in Python

x = 10
print("Initial:", x)

# Add and assign
x += 5
print("After +=:", x)

# Subtract and assign
x -= 3
print("After -=:", x)

# Multiply and assign
x *= 2
print("After *=:", x)

# Divide and assign
x /= 4
print("After /=:", x)

# Floor divide and assign
x //= 2
print("After //=:", x)

# Modulus and assign
x %= 3
print("After %=:", x)

# Exponentiation and assign
x **= 2
print("After **=:", x)
