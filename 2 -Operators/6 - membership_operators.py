
# Membership Operators in Python

fruits = ["apple", "banana", "mango"]

# Check if an element exists
print("Apple exists:", "apple" in fruits)

# Check if an element does not exist
print("Grapes missing:", "grapes" not in fruits)

# Membership in a string
message = "Learn Python"

print("Python exists:", "Python" in message)
print("Java missing:", "Java" not in message)
